// Writes supabase/seed.sql: the course content from content/*/ as plain SQL,
// for running in the Supabase SQL Editor instead of `npm run seed`.
//
//   npm run seed:sql
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getQuestionType } from "../lib/questions/types";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const textArray = (a: string[]) => `array[${a.map(lit).join(", ")}]::text[]`;

const root = join(process.cwd(), "content");
const out: string[] = [
  "-- Generated by `npm run seed:sql` from content/. Safe to re-run.",
  "begin;",
];

for (const slug of readdirSync(root).filter((d) => existsSync(join(root, d, "course.json")))) {
  const c = JSON.parse(readFileSync(join(root, slug, "course.json"), "utf8"));
  const qPath = join(root, slug, "questions.json");
  const questions = existsSync(qPath) ? JSON.parse(readFileSync(qPath, "utf8")) : [];
  const course = `(select id from public.courses where slug = ${lit(c.course.slug)})`;

  out.push(
    `\n-- ${c.course.code}`,
    `insert into public.courses (slug, code, name, position, book, parts) values (${lit(c.course.slug)}, ${lit(c.course.code)}, ${lit(c.course.name)}, ${c.course.position ?? 0}, ${json(c.book ?? {})}, ${json(c.parts ?? {})})`,
    `  on conflict (slug) do update set code = excluded.code, name = excluded.name, position = excluded.position, book = excluded.book, parts = excluded.parts;`,
  );
  for (const ch of c.chapters) {
    out.push(
      `insert into public.chapters (course_id, n, part, title, pages, outline, summary, terms) values (${course}, ${ch.n}, ${ch.part ?? 0}, ${lit(ch.title)}, ${lit(ch.pages ?? "")}, ${textArray(ch.outline ?? [])}, ${textArray(ch.summary ?? [])}, ${json(ch.terms ?? [])})`,
      `  on conflict (course_id, n) do update set part = excluded.part, title = excluded.title, pages = excluded.pages, outline = excluded.outline, summary = excluded.summary, terms = excluded.terms;`,
    );
  }
  out.push(`delete from public.questions where course_id = ${course} and source = 'seed';`);
  questions.forEach((q: Record<string, unknown>, i: number) => {
    const payload = getQuestionType(q.type as string).parsePayload(q);
    out.push(
      `insert into public.questions (course_id, chapter_n, type, prompt, payload, explanation, source, position) values (${course}, ${q.ch ?? "null"}, ${lit(q.type as string)}, ${lit(q.q as string)}, ${json(payload)}, ${lit((q.why as string) ?? "")}, 'seed', ${i});`,
    );
  });
}

out.push("\ncommit;\n");
writeFileSync("supabase/seed.sql", out.join("\n"));
console.log("✓ wrote supabase/seed.sql");
